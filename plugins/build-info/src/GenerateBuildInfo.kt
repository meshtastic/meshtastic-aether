package org.meshtastic.aether.buildinfo

import org.jetbrains.amper.plugins.ExecutionAvoidance
import org.jetbrains.amper.plugins.Output
import org.jetbrains.amper.plugins.TaskAction
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.div
import kotlin.io.path.exists
import kotlin.io.path.readText
import kotlin.io.path.writeText

private const val LABEL = "AETHER_BUILD_LABEL"
private const val CODE = "AETHER_BUILD_CODE"
private const val CHANNEL = "AETHER_BUILD_CHANNEL"

/**
 * Writes `BuildInfo` from AETHER_BUILD_LABEL, AETHER_BUILD_CODE and AETHER_BUILD_CHANNEL, which CI sets together;
 * with none of them set it is a local build. Environment input cannot be fingerprinted, so it runs every build and
 * rewrites the file only when its text changes, which keeps the Kotlin compile up to date.
 */
@TaskAction(executionAvoidance = ExecutionAvoidance.Disabled)
fun generateBuildInfo(@Output outputDir: Path) {
    val source = renderBuildInfo(System.getenv())
    val file = outputDir / "BuildInfo.kt"
    if (file.exists() && file.readText() == source) return
    outputDir.createDirectories()
    file.writeText(source)
}

internal fun renderBuildInfo(env: Map<String, String>): String {
    val set = listOf(LABEL, CODE, CHANNEL).filter { !env[it].isNullOrEmpty() }
    val (label, code, channel) = when (set.size) {
        0 -> Triple("dev", "0", "DEV")
        3 -> Triple(env.getValue(LABEL), env.getValue(CODE), env.getValue(CHANNEL))
        else -> error("$LABEL, $CODE and $CHANNEL are set together; only ${set.joinToString()} is set")
    }
    require(Regex("[0-9A-Za-z.+-]+").matches(label)) { "$LABEL is not a label: '$label'" }
    require(code == "0" && set.isEmpty() || Regex("[1-9][0-9]*").matches(code)) { "$CODE is not a build code: '$code'" }
    val enum = channel.uppercase()
    require(enum in setOf("DEV", "RELEASE", "SNAPSHOT")) { "$CHANNEL is not a channel: '$channel'" }
    return """
        |package org.meshtastic.aether.update
        |
        |/** What this build is, generated by plugins/build-info. A local build is `dev`, code 0, channel DEV. */
        |object BuildInfo {
        |    const val VERSION: String = "$label"
        |
        |    /** The commit count of the built commit, which is also the Android versionCode; 0 for a local build. */
        |    const val CODE: Long = $code
        |
        |    val CHANNEL: Channel = Channel.$enum
        |}
        |
    """.trimMargin()
}
